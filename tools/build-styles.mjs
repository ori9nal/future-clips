// Build the Styles page's examples: one real cover per style, straight from a
// set this engine actually rendered, plus the manifest the app reads.
//
//   node tools/build-styles.mjs
//
// Writes public/styles/<id>.webp and lib/styles-manifest.ts. Re-run after a
// better render and commit both.
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';
import { pathToFileURL } from 'node:url';

const ROOT = process.cwd();
const OUT = path.join(ROOT, 'public', 'styles');

// the set each style is shown with, and the words a clipper would use for it
const SHOW = {
  feed:     { set: 'apex-strength-feed',    name: 'Feed',     word: 'Phone photos, small captions',     for: 'Gym, trading, anything that has to look like a post rather than an ad.' },
  native:   { set: 'apex-strength-native',  name: 'Native',   word: 'Phone photos, big captions',       for: 'The same look with the words bigger — best when the line IS the slide.' },
  bedrock:  { set: 'apex-strength-bedrock', name: 'Bedrock',  word: 'Illustrated character',            for: 'Programmes and how-to: a drawn figure doing the thing, muscles tinted.' },
  rail:     { set: 'northbound-trail-rail', name: 'Rail',     word: 'Designed poster series',           for: 'One named thing per page. Travel, fashion, creator, agency work.' },
  document: { set: 'ledger-pro-document',   name: 'Document', word: 'Numbered text pages',              for: 'When the value is the detail — tables, worked examples, a footnote.' },
  poster:   { set: 'lumen-barrier-poster',  name: 'Poster',   word: 'Loud display type',                for: 'Content about content: hooks, marketing, design education.' },
  pastel:   { set: 'ledger-pro-pastel',     name: 'Pastel',   word: 'Warm pages, serif questions',      for: 'Skincare, beauty, money-calm. Quiet where the others shout.' },
};

const reg = await import(pathToFileURL(path.join(ROOT, 'engine', 'styles', 'registry.mjs')).href);
const byId = Object.fromEntries(reg.STYLES.map((s) => [s.id, s]));

fs.mkdirSync(OUT, { recursive: true });
const rows = [];
for (const [id, show] of Object.entries(SHOW)) {
  const style = byId[id];
  if (!style) { console.warn(`! ${id} is not in the registry, skipped`); continue; }
  const src = path.join(ROOT, 'output', 'sets', show.set, 'slide-1.png');
  if (!fs.existsSync(src)) { console.warn(`! ${id}: no ${src}`); continue; }
  const meta = await sharp(src).metadata();
  await sharp(src).resize(560).webp({ quality: 82 }).toFile(path.join(OUT, `${id}.webp`));
  rows.push({ id, name: show.name, word: show.word, for: show.for, niches: style.niches ?? [], ratio: `${meta.width}x${meta.height}` });
  console.log(`${id.padEnd(9)} ${show.set}  ${meta.width}x${meta.height}`);
}

const ts = `// Generated by tools/build-styles.mjs — do not edit by hand.
// One real cover per style, rendered by this engine, with the words a clipper
// would use for it. Re-run the tool after a better render.
export type StyleCard = { id: string; name: string; word: string; for: string; niches: string[]; ratio: string };
export const STYLE_CARDS: StyleCard[] = ${JSON.stringify(rows, null, 2)};
export const STYLE_IDS = STYLE_CARDS.map((s) => s.id);
`;
fs.writeFileSync(path.join(ROOT, 'lib', 'styles-manifest.ts'), ts);
console.log(`\n${rows.length} styles → public/styles/, lib/styles-manifest.ts`);
